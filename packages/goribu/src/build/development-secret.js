import { randomBytes } from "node:crypto";
import { closeSync, constants, fstatSync, lstatSync, mkdirSync, openSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/** Read only Goribu's own generated secret; app env loading belongs to Wrangler. */
export function getDevelopmentSecret(projectRoot) {
  const directory = join(projectRoot, ".goribu");
  const file = join(directory, "dev-secret");
  let fd;
  try {
    mkdirSync(directory, { recursive: true });
    if (!lstatSync(directory).isDirectory()) throw new Error("Invalid generated directory");
    try {
      writeFileSync(file, randomBytes(32).toString("base64url"), { flag: "wx", mode: 0o600 });
    } catch (error) {
      if (error.code !== "EEXIST") throw error;
    }
    // Refuse redirects to an app-authored file, and bound reads of corrupt state.
    fd = openSync(file, constants.O_RDONLY | constants.O_NOFOLLOW);
    const stat = fstatSync(fd);
    if (!stat.isFile() || stat.size !== 43) throw new Error("Invalid generated secret file");
    const secret = readFileSync(fd, "utf8");
    if (!/^[A-Za-z0-9_-]{43}$/.test(secret) || Buffer.from(secret, "base64url").toString("base64url") !== secret) {
      throw new Error("Invalid generated secret encoding");
    }
    return secret;
  } catch {
    // Do not attach parser errors or file contents to this diagnostic.
    throw new Error("[Goribu] Could not load the generated .goribu/dev-secret. Ensure .goribu is a writable directory and dev-secret is a regular file generated by Goribu. Remove only .goribu/dev-secret and restart `goribu dev` to regenerate it; existing local signed links will expire.");
  } finally {
    if (fd !== undefined) closeSync(fd);
  }
}
