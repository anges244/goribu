import { join, resolve } from "node:path";
import { isApplicationConfig } from "../runtime/application-config.js";
import { writeGeneratedFile } from "./write-generated-file.js";
import { assertWranglerAccepts, assertWranglerPassthrough } from "./wrangler-passthrough.js";

const GENERATED_DIRECTORY = ".goribu";
export const GENERATED_WRANGLER_CONFIG = "goribu.wrangler.jsonc";
// Distinct 32-hex placeholders shaped like real Hyperdrive IDs.
// Deploy must replace both with provisioned IDs before uploading a Worker.
export const GORIBU_HYPERDRIVE_PLACEHOLDER = "00000000000000000000000000000000";
export const GORIBU_HYPERDRIVE_CACHED_PLACEHOLDER = "00000000000000000000000000000001";
const WORKER_FILENAME = "worker.js";
const ASSETS_BINDING = "ASSETS";
const D1_BINDING = "DB";

/**
 * Synthesize the Wrangler configuration from the application config and write it
 * to `<projectRoot>/goribu.wrangler.jsonc`.
 *
 * `goribu.config.js` is the single channel for deploy identity, so the app never
 * hand-writes a Wrangler file. Keeping it at the project root lets Cloudflare
 * find the app's local `.env` / `.dev.vars` beside it. `@cloudflare/vite-plugin`
 * reads this file (via `configPath`) and emits the deploy-ready output.
 *
 * Native fields from the app's `wrangler` block are merged in after Goribu's own.
 * Only then is the result checked: reserved fields and names, Wrangler's schema,
 * and Wrangler's own reader. Apps without the block skip all three.
 *
 * @param {{ projectRoot: string, appConfig: object }} options
 * @returns {{ outputFile: string, config: object }}
 */
export function writeWranglerConfig(options) {
  const projectRoot = options?.projectRoot;
  if (typeof projectRoot !== "string" || projectRoot.length === 0) {
    throw new TypeError(
      "[Goribu] writeWranglerConfig({ projectRoot, appConfig }) requires the application project root.",
    );
  }

  const appConfig = options?.appConfig;
  if (!isApplicationConfig(appConfig)) {
    throw new TypeError(
      "[Goribu] writeWranglerConfig({ appConfig }) requires the defineConfig() result from goribu.config.js.",
    );
  }

  const root = resolve(projectRoot);
  const outputFile = join(root, GENERATED_WRANGLER_CONFIG);
  const config = synthesizeWranglerConfig(appConfig);
  if (appConfig.wrangler !== undefined) assertWranglerPassthrough({ appConfig, config });

  writeGeneratedFile(
    outputFile,
    `// Generated by Goribu. Do not edit; configure goribu.config.js instead.\n${JSON.stringify(config, null, 2)}\n`,
  );
  if (appConfig.wrangler !== undefined) assertWranglerAccepts(outputFile);
  return Object.freeze({ outputFile, config });
}

function synthesizeWranglerConfig(appConfig) {
  const config = {
    name: appConfig.name,
    main: `${GENERATED_DIRECTORY}/${WORKER_FILENAME}`,
    compatibility_date: appConfig.compatibilityDate,
    // drop-trailing-slash matches the Worker's own canonicalization, so a static
    // asset and a dynamically rendered route answer the same URL the same way.
    assets: { binding: ASSETS_BINDING, html_handling: "drop-trailing-slash" },
    // Wrangler re-enables workers.dev on every deploy unless this is explicit.
    workers_dev: appConfig.workersDev,
    // Goribu deploys production only; per-version preview URLs would just be
    // more public addresses.
    preview_urls: false,
  };

  const flags = [...appConfig.compatibilityFlags];
  if (appConfig.database?.type === "postgres" && !flags.includes("nodejs_compat")) {
    flags.push("nodejs_compat");
  }
  if (flags.length > 0) {
    config.compatibility_flags = flags;
  }

  if (appConfig.database?.type === "d1") {
    config.d1_databases = [
      {
        binding: D1_BINDING,
        database_name: appConfig.database.name,
        // Wrangler uses the preview id as the local SQLite store key. The
        // application-authored name keeps the same local database stable while
        // Goribu owns the production UUID separately at deploy time.
        preview_database_id: appConfig.database.name,
      },
    ];
  }

  if (appConfig.database?.type === "postgres") {
    config.hyperdrive = [
      { binding: "POSTGRES", id: appConfig.database.hyperdriveId ?? GORIBU_HYPERDRIVE_PLACEHOLDER },
      { binding: "POSTGRES_CACHED", id: appConfig.database.hyperdriveCachedId ?? GORIBU_HYPERDRIVE_CACHED_PLACEHOLDER },
    ];
  }

  if (appConfig.kv !== undefined) {
    config.kv_namespaces = [{
      binding: "KV",
      // A stable local store key; the production id arrives only during deploy.
      preview_id: appConfig.kv.name,
    }];
  }

  if (appConfig.r2 !== undefined) {
    const r2 = appConfig.r2;
    const jurisdiction = r2.jurisdiction === undefined ? {} : { jurisdiction: r2.jurisdiction };
    config.r2_buckets = [{ binding: "R2", bucket_name: r2.name, ...jurisdiction }];
    if (r2.private !== undefined) {
      config.r2_buckets.push({ binding: "R2_PRIVATE", bucket_name: r2.private.name, ...jurisdiction });
    }
  }

  // The snapshot is deeply frozen JSON, and reserved fields never collide.
  return { ...config, ...appConfig.wrangler };
}
