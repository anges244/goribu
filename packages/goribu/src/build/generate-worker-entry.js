import { mkdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve, sep } from "node:path";

const GENERATED_DIRECTORY = ".goribu";
const WORKER_FILENAME = "worker.js";
const PAGE_FILE = "src/page.jsx";

/**
 * Generate the Worker entry into `<projectRoot>/.goribu/worker.js`.
 *
 * This is the walking-skeleton generator: it wires one hardcoded page into a
 * Worker that streams it through `renderToReadableStream`. There is no routing
 * yet, so every request renders the same page; Block 2 replaces the hardcoded
 * page with a scanned route tree.
 *
 * @param {{ projectRoot: string }} options
 * @returns {{ outputFile: string, source: string }}
 */
export function writeWorkerEntry(options) {
  const projectRoot = options?.projectRoot;
  if (typeof projectRoot !== "string" || projectRoot.length === 0) {
    throw new TypeError(
      "[Goribu] writeWorkerEntry({ projectRoot }) requires the application project root.",
    );
  }

  const root = resolve(projectRoot);
  const outputFile = join(root, GENERATED_DIRECTORY, WORKER_FILENAME);
  const pageFile = join(root, PAGE_FILE);

  let pageStats;
  try {
    pageStats = statSync(pageFile);
  } catch (cause) {
    if (cause?.code === "ENOENT") {
      throw new Error(
        `[Goribu] Cannot generate the Worker entry because ${JSON.stringify(pageFile)} is missing. ` +
          `Create ${PAGE_FILE} that default-exports a React component.`,
        { cause },
      );
    }
    throw new Error(
      `[Goribu] Could not inspect ${JSON.stringify(pageFile)}. ` +
        `Make sure the project directory is readable and try again. ${cause.message}`,
      { cause },
    );
  }

  if (!pageStats.isFile()) {
    throw new Error(
      `[Goribu] Cannot generate the Worker entry because ${JSON.stringify(pageFile)} is not a regular file. ` +
        `Replace it with ${PAGE_FILE} that default-exports a React component.`,
    );
  }

  const pageSpecifier = relativeImportSpecifier(dirname(outputFile), pageFile);
  const source = generateWorkerEntrySource(pageSpecifier);

  mkdirSync(dirname(outputFile), { recursive: true });
  writeFileSync(outputFile, source, "utf8");
  return Object.freeze({ outputFile, source });
}

function generateWorkerEntrySource(pageSpecifier) {
  return `// Generated by Goribu. Do not edit.
import { createElement } from "react";
import { renderToReadableStream } from "react-dom/server.edge";
import Page from ${JSON.stringify(pageSpecifier)};

export default {
  async fetch() {
    const stream = await renderToReadableStream(
      createElement(
        "html",
        null,
        createElement("head", null, createElement("meta", { charSet: "utf-8" })),
        createElement(
          "body",
          null,
          createElement("div", { id: "root" }, createElement(Page)),
        ),
      ),
    );
    return new Response(stream, {
      headers: { "content-type": "text/html; charset=utf-8" },
    });
  },
};
`;
}

function relativeImportSpecifier(fromDirectory, source) {
  let specifier = relative(fromDirectory, source).split(sep).join("/");
  if (!specifier.startsWith(".")) specifier = `./${specifier}`;

  // ESM treats these characters as URL syntax. Escape them so valid source
  // filenames remain filesystem paths rather than query or fragment delimiters.
  return specifier
    .replaceAll("%", "%25")
    .replaceAll("?", "%3F")
    .replaceAll("#", "%23");
}
